export function generateStatusTableMarkdown(): string {
  const header = `| # | Milestone | Gate | Status | Evidence |
|---|---|---|---|---|`;

  const rows = MILESTONES.map((m) => {
    const statusFormatted =
      m.status === 'PASSED'
        ? '✅ **PASSED**'
        : m.status === 'IN PROGRESS'
          ? '🟡 **IN PROGRESS**'
          : '⬜ NOT STARTED';
    return `| ${m.id} | ${m.name} | \`${m.gate}\` | ${statusFormatted} | ${m.evidence} |`;
  });

  return [header, ...rows].join('\n');
}

export function updateFileTable(filePath: string) {
  if (!fs.existsSync(filePath)) return;

  const content = fs.readFileSync(filePath, 'utf8');
  const startMarker = '<!-- STATUS_TABLE_START -->';
  const endMarker = '<!-- STATUS_TABLE_END -->';

  const tableMd = generateStatusTableMarkdown();

  if (content.includes(startMarker) && content.includes(endMarker)) {
    const regex = new RegExp(`${startMarker}[\\s\\S]*?${endMarker}`, 'g');
    const updated = content.replace(regex, `${startMarker}\n${tableMd}\n${endMarker}`);
    fs.writeFileSync(filePath, updated, 'utf8');
    console.log(`Updated status table in: ${filePath}`);
  } else {
    // Look for markdown table after ## Status Table
    const headerRegex = /## Status Table[\s\S]*?(?=\n## |\n---|$)/;
    if (headerRegex.test(content)) {
      const section = `## Status Table\n\n> **This table is generated by \`npm run status:update\` — never hand-edited.**\n> A milestone is DONE when its \`npm run verify:*\` gate runs green, not when its files exist.\n\n<!-- STATUS_TABLE_START -->\n${tableMd}\n<!-- STATUS_TABLE_END -->\n`;
      const updated = content.replace(headerRegex, section);
      fs.writeFileSync(filePath, updated, 'utf8');
      console.log(`Replaced status table in: ${filePath}`);
    }
  }
}

function main() {
  console.log('Regenerating status table from verified milestone gates...');
  updateFileTable(path.join(REPO_ROOT, 'README.md'));
  updateFileTable(path.join(REPO_ROOT, 'docs/milestones/README.md'));
  console.log('Status tables up to date.');
}

main();
